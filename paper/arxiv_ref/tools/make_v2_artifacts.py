MAC = {}


_PREV = [""]


def mac(name, val, src):
    assert name.isalpha(), name
    assert name not in MAC, name
    if src.startswith("same"):      # "same: DA" repeats the source file of the previous macro
        prev = _PREV[0]
        prefix = prev.split(":")[0] if ":" in prev else prev.split(" ")[0]
        src = prefix + (":" + src.split(":", 1)[1] if ":" in src else src[4:])
    else:
        _PREV[0] = src
    MAC[name] = (str(val), src)


def rows(name, base=RES):
    with open(base / name, newline="") as f:
        return [r for r in csv.DictReader(f) if not r[next(iter(r))].startswith("#")]


def jl(path):
    with open(path) as f:
        return json.load(f)


def tt(s):
    return r"\texttt{" + s.replace("_", r"\_") + "}"


def pc(x, nd=2):
    """0.0881 -> '8.81' (percent without the sign)."""
    return f"{100.0 * x:.{nd}f}"


def pci(blk, key="wilson95", nd=2):
    lo, hi = blk[key]
    return f"{pc(blk['rate'], nd)}\\,\\% [{pc(lo, nd)}, {pc(hi, nd)}]"


def f4(x):
    return f"{x:.4f}"


def th(n):
    return f"{int(n):,}".replace(",", "{,}")


# ---------------------------------------------------------------- shipped defaults and the derived test
hpp = (ROOT / "strata_core/include/strata_core/layered_map.hpp").read_text()
D = {k: float(re.search(r"double %s\{([0-9.]+)\}" % k, hpp).group(1)) for k in ("m0", "m1", "alpha", "beta")}
NMAX = int(re.search(r"int n_max_undecided\{(\d+)\}", hpp).group(1))
TGATE = int(re.search(r"period_windows\{(\d+)\}", (ROOT / "strata_core/include/strata_core/periodicity.hpp").read_text()).group(1))
L_HIT = math.log(D["m1"] / D["m0"])
L_MISS = math.log((1 - D["m1"]) / (1 - D["m0"]))
A = math.log((1 - D["beta"]) / D["alpha"])
B = math.log(D["beta"] / (1 - D["alpha"]))
CEIL = A + 2 * L_HIT
M_STAR = -L_MISS / (L_HIT - L_MISS)
lat, l_ = 0, 0.0
while l_ < A:
    l_ = min(l_ + L_HIT, CEIL)
    lat += 1
dem, l_ = 0, CEIL
while l_ > CEIL - A:
    l_ += L_MISS
    dem += 1
SRC_DEF = "strata_core/include/strata_core/layered_map.hpp (shipped defaults), derived as deriveSprt() derives them"

