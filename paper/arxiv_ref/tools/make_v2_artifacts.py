ez = m0_leg * math.exp(LEAK_LAM * lh0) + (1 - m0_leg) * math.exp(LEAK_LAM * lm0)
LEAK_RATIO = math.exp((1 - LEAK_LAM) * -LEAK_L) * ez
mac("SqLeakRatio", f"{LEAK_RATIO:.2f}", "analytic: exp((1 - lambda)|l|) E_{m0}[exp(lambda Z)] at lambda 0.97, l = -4, increments (0.85, -0.4)")
mac("SqLeakLevel", f"{-LEAK_L:.0f}", "the level l = -4 of that ratio (no clamp acts in the step)")

