m1_leg = m0_leg * math.exp(lh0)
mac("SqLegMzero", f4(m0_leg), "closed form: m0 = (e^{l_miss} - 1) / (e^{l_miss} - e^{l_hit}) at (0.85, -0.4)")
mac("SqLegMone", f4(m1_leg), "m1 = m0 e^{l_hit} at (0.85, -0.4)")
mac("SqLegThreshold", f"{math.log(4):.3f}", "logit(0.8) = ln 4")
mac("SqLegBound", f"{math.exp(-math.log(4)):.2f}", "exp(-ln 4) = 1/4")
mac("SqLegMstar", f"{0.4 / (0.85 + 0.4):.2f}", "-l_miss / (l_hit - l_miss) at (0.85, -0.4)")

# the leak: E[exp(l')] / exp(l) for l' = lambda (l + Z), Z the log-likelihood-ratio increment, hit rate m0 of the v0.1 pair
