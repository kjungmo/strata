mac("SqVille", f"{math.exp(-A):.4f}", "exp(-A) = alpha / (1 - beta) at the shipped defaults")
mac("SqVilleBeta", f"{math.exp(B):.4f}", "exp(B) = beta / (1 - alpha) at the shipped defaults")
mac("SqRatioA", f"{math.exp(A):.0f}", "exp(A) = (1 - beta) / alpha")

# the v0.1 increments as a test
