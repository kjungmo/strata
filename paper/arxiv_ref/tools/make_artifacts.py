def med(v):
    v = sorted(v)
    return v[len(v) // 2] if len(v) % 2 else 0.5 * (v[len(v) // 2 - 1] + v[len(v) // 2])


def mem(b):
    b = float(b)
    if b < 1e6:
        return f"{b/1e3:.0f}~KB"
    mb = b / 1e6
    return (f"{mb:.2f}" if mb < 10 else f"{mb:.1f}") + "~MB"


