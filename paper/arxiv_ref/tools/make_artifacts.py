def wilson(k, n, z=1.959964):
    p = k / n
    c = (p + z * z / (2 * n)) / (1 + z * z / n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, c - h), min(1.0, c + h)


def ci(k, n, d=3):
    lo, hi = wilson(k, n)
    return f"[{lo:.{d}f}, {hi:.{d}f}]"


