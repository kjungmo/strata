def rstar(level):
    lo_, hi_ = 1.0, 200.0
    for _ in range(200):
        mid_ = 0.5 * (lo_ + hi_)
        if mid_ * math.exp(1.0 - mid_) > level / H_E2:
            lo_ = mid_
        else:
            hi_ = mid_
    return 0.5 * hi_


