#!/usr/bin/env python3
"""Formats the phase 1b result tables into results_p1b/P1B_REPORT.md. It computes no statistic: every number is copied
from a table written by analyze_p1b.py, derive_defaults.py, freeze_prereg.py or a meta file of the probe.

    python3 -I make_report_p1b.py --results-dir results_p1b --prereg-dir . --out results_p1b/P1B_REPORT.md
"""
import argparse
import csv
import json
import os
import subprocess
import sys


def load(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def meta(path):
    d = {}
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                if "=" in line:
                    k, v = line.rstrip("\n").split("=", 1)
                    d[k] = v
    return d


def table(rows, cols, heads=None):
    if not rows:
        return "_no rows_\n"
    heads = heads or cols
    out = ["| " + " | ".join(heads) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"


def git(args, cwd):
    try:
        return subprocess.check_output(["git", "-C", cwd] + args, stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


def first_last(logdir):
    """Earliest START and latest END line over all step logs: the chronology of the measurements."""
    starts = []
    for fn in sorted(os.listdir(logdir)) if os.path.isdir(logdir) else []:
        if not fn.endswith(".log") or fn.startswith("build_"):
            continue
        with open(os.path.join(logdir, fn)) as f:
            for line in f:
                if line.startswith("START "):
                    starts.append((line.split()[1], fn))
                    break
    starts.sort()
    return starts


def gap_table(rows, dataset, extra_filter=None, n_min="5"):
    out = []
    for r in rows:
        if r["dataset"] != dataset or r["N_min"] != n_min:
            continue
        if extra_filter and not extra_filter(r):
            continue
        out.append(r)
    return out


GAP_COLS = ["res_m", "W", "miss", "pair", "n_structure", "n_clutter", "q_s_p10", "q_c_p90", "gap", "gap_ci95_block_lo", "gap_ci95_block_hi",
            "q_s_ci95_block_lo", "q_s_ci95_block_hi", "q_c_ci95_block_lo", "q_c_ci95_block_hi", "gap_ge_0.15", "m0_rounded", "m1_rounded"]
GAP_HEADS = ["res", "W", "miss", "pair", "N struct", "N clutter", "q_s", "q_c", "gap", "gap CI lo", "gap CI hi", "q_s CI lo", "q_s CI hi",
             "q_c CI lo", "q_c CI hi", "gap>=0.15", "m0", "m1"]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", required=True)
    ap.add_argument("--prereg-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    rd = a.results_dir
    gap = load(os.path.join(rd, "p1b_gap.csv"))
    gates = load(os.path.join(rd, "p1b_gates.csv"))
    L = []
    P = L.append
    P("# Phase 1b report: gates, W = 15, Keble 02 in 3D, and the freeze")
    P("")
    P("Generated by `make_report_p1b.py` from the committed tables. It computes nothing. Definitions: `PREREG_P1B.md` (Amendment 2) and `PREREG_P1.md`.")
    P("")
    # ---- chronology
    P("## 1. Chronology")
    P("")
    repo = os.path.abspath(os.path.join(a.prereg_dir, "..", ".."))
    log = git(["log", "--reverse", "--format=%h %cI %s", "2db4f2c^..HEAD", "--", "paper/experiments/realdata"], repo)
    P("Commits of the branch since the stat record (oldest first):")
    P("")
    for line in log.splitlines():
        P("- " + line)
    P("")
    steps = []
    logdir = os.path.join(rd, "logs")
    for fn in sorted(os.listdir(logdir)) if os.path.isdir(logdir) else []:
        if not fn.endswith(".log") or fn.startswith("build_"):
            continue
        st = en = rc = ""
        with open(os.path.join(logdir, fn)) as f:
            for line in f:
                if line.startswith("START "):
                    st = line.split()[1]
                elif line.startswith("END "):
                    parts = line.split()
                    en = parts[1]
                    rc = parts[2].replace("rc=", "") if len(parts) > 2 else ""
        steps.append({"step": fn[:-4], "start": st, "end": en, "rc": rc})
    steps.sort(key=lambda r: r["start"])
    P("Step logs (`results_p1b/logs/`, sorted by start; each carries host, load and the command):")
    P("")
    P(table(steps, ["step", "start", "end", "rc"]))
    if steps:
        P("The first measurement step (`%s`) started %s, after the commits of the stat record, Amendment 2 and the code." % (steps[0]["step"], steps[0]["start"]))
        P("")
    # ---- gates
    P("## 2. Gates G1 and G2 on all calibration sequences")
    P("")
    P(table(gates, ["sequence", "class", "g1_accepted", "g1_p50_m", "g1_p90_m", "g1_limit_p50_m", "g1_limit_p90_m", "g1_pass", "g2_queries",
                    "g2_matched_share", "g2_p50_m", "g2_p90_m", "g2_limit_p50_m", "g2_limit_p90_m", "g2_pass", "gates_pass", "old_gate_p50_m", "old_gate_p90_m"],
            ["sequence", "class", "G1 patches", "G1 median m", "G1 p90 m", "limit", "limit", "G1", "G2 queries", "matched", "G2 median m", "G2 p90 m", "limit", "limit", "G2", "both",
             "old gate median m", "old gate p90 m"]))
    P("Status by the rule of `PREREG_P1B.md` section 3.3 (a sequence that fails G1 or G2 is excluded from headline tables and reported as EXCLUDED):")
    P("")
    status = {}
    for g in gates:
        ok = g.get("gates_pass") == "PASS"
        why = []
        if g.get("g1_pass") != "PASS":
            why.append("G1 (%s patches, median %s m, p90 %s m)" % (g.get("g1_accepted"), g.get("g1_p50_m"), g.get("g1_p90_m")))
        if g.get("g2_pass") != "PASS":
            why.append("G2 (matched %s, median %s m, p90 %s m)" % (g.get("g2_matched_share"), g.get("g2_p50_m"), g.get("g2_p90_m")))
        status[g["sequence"]] = ok
        P("- `%s`: **%s**%s" % (g["sequence"], "INCLUDED" if ok else "EXCLUDED", "" if ok else " by " + " and ".join(why)))
    P("")
    if not any(status.values()):
        P("No calibration sequence passes both gates, so no table below is a headline table. All tables are printed for the record and marked EXCLUDED.")
        P("")
    def tag(*seqs):
        return "" if seqs and all(status.get(x, False) for x in seqs) else " (EXCLUDED)"
    # ---- W = 15
    P("## 3. LILocBench, W = 15 steps (1.0 s)%s" % tag("lil_mapping", "lil_static_0", "lil_dynamics_0"))
    P("")
    P("Primary row: resolution 0.05 m, `structure@static_0_vs_clutter@dynamics_0`, N_min = 5. Intervals: block bootstrap (tiles of 10 m, 2000 replicates, seed 20261014).")
    P("")
    P(table(gap_table(gap, "lil"), GAP_COLS, GAP_HEADS))
    P("N_min sensitivity of the primary pair:")
    P("")
    P(table([r for r in gap if r["dataset"] == "lil" and r["res_m"] == "0.05" and r["pair"].startswith("structure@static_0_vs_clutter@dynamics_0")],
            ["N_min", "n_structure", "n_clutter", "q_s_p10", "q_c_p90", "gap", "gap_ci95_block_lo", "gap_ci95_block_hi", "m0_rounded", "m1_rounded"]))
    # ---- Keble
    P("## 4. Spires Keble 02%s" % tag("keble02"))
    P("")
    P("### 4.1 TLS area, offset, conversion, labels")
    P("")
    for name in ("spires_tls", "spires_offset", "spires_convert", "labels_keble02_r0.2", "labels_keble02_r0.1"):
        m = meta(os.path.join(rd, "meta", name + ".meta"))
        if m:
            P("`%s`: " % name + ", ".join("%s=%s" % (k, v) for k, v in m.items() if k not in ("seconds", "peak_rss_kb")))
            P("")
    P("### 4.2 Hit-rate gap, both miss definitions")
    P("")
    P(table(gap_table(gap, "keble02"), GAP_COLS, GAP_HEADS))
    P("### 4.3 Grazing-miss diagnostic")
    P("")
    P(table(load(os.path.join(rd, "p1b_grazing.csv")), ["dataset", "res_m", "W", "structure_miss_events", "events_endpoint_within_1_voxel", "share_events",
                                                         "structure_miss_windows", "miss_windows_with_such_event", "share_windows",
                                                         "structure_touched_windows_today", "structure_touched_windows_refined", "share_touched_windows_removed"]))
    # ---- KITTI
    P("## 5. KITTI 00, refined miss (secondary check; equivalence of the lean probe)%s" % tag("kitti00"))
    P("")
    eq = os.path.join(rd, "equivalence_kth.txt")
    if os.path.exists(eq):
        with open(eq) as f:
            P("```\n" + f.read().rstrip() + "\n```")
    P("")
    P(table(gap_table(gap, "kth00", lambda r: r["pair"] in ("structure_vs_moving", "solid_vs_moving")), GAP_COLS, GAP_HEADS))
    # ---- Option C
    P("## 6. Option C evidence (matched hit rate, lag-1 autocorrelation)")
    P("")
    P(table([r for r in load(os.path.join(rd, "p1b_matched_band.csv"))], ["dataset", "res_m", "W", "pair", "band", "n_structure", "structure_lag1_mean",
                                                                          "n_clutter", "clutter_lag1_mean", "auc_lag1_structure_over_clutter"]))
    # ---- freeze
    P("## 7. Freeze")
    P("")
    pj = os.path.join(a.prereg_dir, "PREREG.json")
    if os.path.exists(pj):
        with open(pj) as f:
            fr = json.load(f)
        for k in ("grid2d", "voxel3d"):
            d = fr[k]
            P("- `%s`: **%s**%s" % (k, d["status"], (", branch %s" % d["branch"]) if "branch" in d else ""))
            if "m0" in d:
                P("  - m0 = %.2f, m1 = %.2f, alpha = beta = %.2f, ceiling = %.4f, n_max = %d, miss = %s" % (d["m0"], d["m1"], d["alpha"], d["ceiling"], d["n_max_undecided"], d["miss_definition"]))
            for r in d.get("reasons", []):
                P("  - reason: %s" % r)
        P("")
        P("Full text: `PREREG.md`.")
    P("")
    # ---- exploratory
    ex = os.path.join(rd, "exploratory")
    P("## 8. Exploratory and post hoc (these runs set nothing)")
    P("")
    rows = []
    if os.path.isdir(ex):
        for fn in sorted(os.listdir(ex)):
            if fn.startswith("gate2d_") and fn.endswith(".meta"):
                m = meta(os.path.join(ex, fn))
                rows.append({"run": fn[:-5], "steps": m.get("steps"), "G1 patches": m.get("g1_accepted"), "G1 median m": "%.4f" % float(m["g1_thickness_m_p50"]),
                             "G1 p90 m": "%.4f" % float(m["g1_thickness_m_p90"]), "G2 median m": "%.4f" % float(m["g2_d_m_p50"])})
        m = meta(os.path.join(ex, "gate_spires_structure_filter.meta"))
        if m:
            rows.append({"run": "keble02, returns inside TLS structure voxels only", "steps": m.get("steps"), "G1 patches": m.get("g1_accepted"),
                         "G1 median m": "%.4f" % float(m["g1_thickness_m_p50"]), "G1 p90 m": "%.4f" % float(m["g1_thickness_m_p90"]), "G2 median m": "%.4f" % float(m["g2_d_m_p50"])})
    P("G1 on slices and on single lasers (same code and thresholds as the gate; limits 0.10 m / 0.20 m in 2D, 0.20 m / 0.40 m in 3D):")
    P("")
    P(table(rows, ["run", "steps", "G1 patches", "G1 median m", "G1 p90 m", "G2 median m"]))
    kc = os.path.join(ex, "keble_clutter_r0.2_W10_today.txt")
    if os.path.exists(kc):
        P("Who are the Keble 02 clutter cells with a high hit rate (`explore_keble_clutter.py`)?")
        P("")
        with open(kc) as f:
            P("```\n" + f.read().rstrip() + "\n```")
        P("")
    # ---- replay
    P("## 9. Replay of the derived test over the calibration run sequences")
    P("")
    rp = os.path.join(rd, "replay", "replay_p1b_out.txt")
    if os.path.exists(rp):
        with open(rp) as f:
            P("```\n" + f.read().rstrip() + "\n```")
    P("")
    P("Shares are over cells of the calibration sequences. `[W ...]` is the Wilson 95 % interval (cells treated as independent), `[B ...]` the block bootstrap over 10 m tiles. Neither is a held-out estimate.")
    P("")
    ar = os.path.join(rd, "advice_replay", "run.log")
    P("## 10. The advisor's replay scripts, re-run")
    P("")
    if os.path.exists(ar):
        with open(ar) as f:
            P("```\n" + f.read().rstrip() + "\n```")
    P("")
    cm = os.path.join(rd, "test_split_stat_compare.md")
    P("## 11. Test-split access record")
    P("")
    if os.path.exists(cm):
        with open(cm) as f:
            txt = f.read()
        P(txt)
    P("")
    out = "\n".join(L)
    with open(a.out, "w") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
