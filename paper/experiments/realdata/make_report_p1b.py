#!/usr/bin/env python3
"""Formats the phase 1b result tables into results_p1b/P1B_REPORT.md. It computes no statistic: every number is copied
from a table written by analyze_p1b.py, derive_defaults.py, freeze_prereg.py or a meta file of the probe.

    python3 -I make_report_p1b.py --results-dir results_p1b --prereg-dir . --out results_p1b/P1B_REPORT.md
"""
import argparse
import csv
import json
import os
import subprocess
import sys


def load(path):
    if not os.path.exists(path):
        return []
    with open(path) as f:
        return list(csv.DictReader(f))


def meta(path):
    d = {}
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                if "=" in line:
                    k, v = line.rstrip("\n").split("=", 1)
                    d[k] = v
    return d


def table(rows, cols, heads=None):
    if not rows:
        return "_no rows_\n"
    heads = heads or cols
    out = ["| " + " | ".join(heads) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |")
    return "\n".join(out) + "\n"


def git(args, cwd):
    """Runs git in cwd and fails loudly: a wrong path must never give an empty chronology (Opus finding 1, phase 1b)."""
    try:
        return subprocess.check_output(["git", "-C", cwd] + args, stderr=subprocess.PIPE).decode().strip()
    except subprocess.CalledProcessError as e:
        raise RuntimeError("git %s failed in %s (rc=%d): %s" % (" ".join(args), cwd, e.returncode, e.stderr.decode().strip()))


def repo_root(start):
    """The root of the repository that contains `start` (not a fixed number of levels up)."""
    return git(["rev-parse", "--show-toplevel"], os.path.abspath(start))


def laser_optima(csv_path):
    """Per-laser offset optimum of a P1 offset table: the dt with the fewest occupied cells, front and rear separately."""
    rows = load(csv_path)
    if not rows:
        return None
    out = {}
    for k in ("c_front", "c_rear", "score"):
        b = min(rows, key=lambda r: int(r[k]))
        out[k] = (b["dt_s"], b[k])
    return out


def first_last(logdir):
    """Earliest START and latest END line over all step logs: the chronology of the measurements."""
    starts = []
    for fn in sorted(os.listdir(logdir)) if os.path.isdir(logdir) else []:
        if not fn.endswith(".log") or fn.startswith("build_"):
            continue
        with open(os.path.join(logdir, fn)) as f:
            for line in f:
                if line.startswith("START "):
                    starts.append((line.split()[1], fn))
                    break
    starts.sort()
    return starts


def gap_table(rows, dataset, extra_filter=None, n_min="5"):
    out = []
    for r in rows:
        if r["dataset"] != dataset or r["N_min"] != n_min:
            continue
        if extra_filter and not extra_filter(r):
            continue
        out.append(r)
    return out


GAP_COLS = ["res_m", "W", "miss", "pair", "n_structure", "n_clutter", "q_s_p10", "q_c_p90", "gap", "gap_ci95_block_lo", "gap_ci95_block_hi",
            "q_s_ci95_block_lo", "q_s_ci95_block_hi", "q_c_ci95_block_lo", "q_c_ci95_block_hi", "gap_ge_0.15", "m0_rounded", "m1_rounded"]
GAP_HEADS = ["res", "W", "miss", "pair", "N struct", "N clutter", "q_s", "q_c", "gap", "gap CI lo", "gap CI hi", "q_s CI lo", "q_s CI hi",
             "q_c CI lo", "q_c CI hi", "gap>=0.15", "m0", "m1"]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", required=True)
    ap.add_argument("--prereg-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    rd = a.results_dir
    gap = load(os.path.join(rd, "p1b_gap.csv"))
    gates = load(os.path.join(rd, "p1b_gates.csv"))
    L = []
    P = L.append
    P("# Phase 1b report: gates, W = 15, Keble 02 in 3D, and the freeze")
    P("")
    P("Generated by `make_report_p1b.py` from the committed tables. It computes nothing. Definitions: `PREREG_P1B.md` (Amendment 2) and `PREREG_P1.md`.")
    P("")
    # ---- chronology
    P("## 1. Chronology")
    P("")
    repo = repo_root(a.prereg_dir)
    log = git(["log", "--reverse", "--format=%h %cI %s", "2db4f2c^..HEAD", "--", "paper/experiments/realdata"], repo)
    if not log.strip():
        raise RuntimeError("the chronology is empty: no commit in 2db4f2c^..HEAD touches paper/experiments/realdata")
    P("Commits of the branch since the stat record (oldest first):")
    P("")
    for line in log.splitlines():
        P("- " + line)
    P("")
    steps = []
    logdir = os.path.join(rd, "logs")
    for fn in sorted(os.listdir(logdir)) if os.path.isdir(logdir) else []:
        if not fn.endswith(".log") or fn.startswith("build_"):
            continue
        st = en = rc = ""
        with open(os.path.join(logdir, fn)) as f:
            for line in f:
                if line.startswith("START "):
                    st = line.split()[1]
                elif line.startswith("END "):
                    parts = line.split()
                    en = parts[1]
                    rc = parts[2].replace("rc=", "") if len(parts) > 2 else ""
        steps.append({"step": fn[:-4], "start": st, "end": en, "rc": rc})
    steps.sort(key=lambda r: r["start"])
    P("Step logs (`results_p1b/logs/`, sorted by start; each carries host, load and the command):")
    P("")
    P(table(steps, ["step", "start", "end", "rc"]))
    if steps:
        P("The first measurement step (`%s`) started %s, after the commits of the stat record, Amendment 2 and the code." % (steps[0]["step"], steps[0]["start"]))
        P("")
    # ---- gates
    P("## 2. Gates G1 and G2 on all calibration sequences")
    P("")
    P(table(gates, ["sequence", "class", "g1_accepted", "g1_p50_m", "g1_p90_m", "g1_limit_p50_m", "g1_limit_p90_m", "g1_pass", "g2_queries",
                    "g2_matched_share", "g2_p50_m", "g2_p90_m", "g2_limit_p50_m", "g2_limit_p90_m", "g2_pass", "gates_pass", "old_gate_p50_m", "old_gate_p90_m"],
            ["sequence", "class", "G1 patches", "G1 median m", "G1 p90 m", "limit", "limit", "G1", "G2 queries", "matched", "G2 median m", "G2 p90 m", "limit", "limit", "G2", "both",
             "old gate median m", "old gate p90 m"]))
    P("Status by the rule of `PREREG_P1B.md` section 3.3 (a sequence that fails G1 or G2 is excluded from headline tables and reported as EXCLUDED):")
    P("")
    status = {}
    for g in gates:
        ok = g.get("gates_pass") == "PASS"
        why = []
        if g.get("g1_pass") != "PASS":
            why.append("G1 (%s patches, median %s m, p90 %s m)" % (g.get("g1_accepted"), g.get("g1_p50_m"), g.get("g1_p90_m")))
        if g.get("g2_pass") != "PASS":
            why.append("G2 (matched %s, median %s m, p90 %s m)" % (g.get("g2_matched_share"), g.get("g2_p50_m"), g.get("g2_p90_m")))
        status[g["sequence"]] = ok
        P("- `%s`: **%s**%s" % (g["sequence"], "INCLUDED" if ok else "EXCLUDED", "" if ok else " by " + " and ".join(why)))
    P("")
    if not any(status.values()):
        P("No calibration sequence passes both gates, so no table below is a headline table. All tables are printed for the record and marked EXCLUDED.")
        P("")
    def tag(*seqs):
        return "" if seqs and all(status.get(x, False) for x in seqs) else " (EXCLUDED)"
    # ---- W = 15
    P("## 3. LILocBench, W = 15 steps (1.0 s)%s" % tag("lil_mapping", "lil_static_0", "lil_dynamics_0"))
    P("")
    P("Primary row: resolution 0.05 m, `structure@static_0_vs_clutter@dynamics_0`, N_min = 5. Intervals: block bootstrap (tiles of 10 m, 2000 replicates, seed 20261014).")
    P("")
    P(table(gap_table(gap, "lil"), GAP_COLS, GAP_HEADS))
    P("N_min sensitivity of the primary pair:")
    P("")
    P(table([r for r in gap if r["dataset"] == "lil" and r["res_m"] == "0.05" and r["pair"].startswith("structure@static_0_vs_clutter@dynamics_0")],
            ["N_min", "n_structure", "n_clutter", "q_s_p10", "q_c_p90", "gap", "gap_ci95_block_lo", "gap_ci95_block_hi", "m0_rounded", "m1_rounded"]))
    # ---- Keble
    P("## 4. Spires Keble 02%s" % tag("keble02"))
    P("")
    P("### 4.1 TLS area, offset, conversion, labels")
    P("")
    for name in ("spires_tls", "spires_offset", "spires_convert", "labels_keble02_r0.2", "labels_keble02_r0.1"):
        m = meta(os.path.join(rd, "meta", name + ".meta"))
        if m:
            P("`%s`: " % name + ", ".join("%s=%s" % (k, v) for k, v in m.items() if k not in ("seconds", "peak_rss_kb")))
            P("")
    P("### 4.2 Hit-rate gap, both miss definitions")
    P("")
    P(table(gap_table(gap, "keble02"), GAP_COLS, GAP_HEADS))
    P("### 4.3 Grazing-miss diagnostic")
    P("")
    P(table(load(os.path.join(rd, "p1b_grazing.csv")), ["dataset", "res_m", "W", "structure_miss_events", "events_endpoint_within_1_voxel", "share_events",
                                                         "structure_miss_windows", "miss_windows_with_such_event", "share_windows",
                                                         "structure_touched_windows_today", "structure_touched_windows_refined", "share_touched_windows_removed"]))
    # ---- KITTI
    P("## 5. KITTI 00, refined miss (secondary check; equivalence of the lean probe)%s" % tag("kitti00"))
    P("")
    eq = os.path.join(rd, "equivalence_kth.txt")
    if os.path.exists(eq):
        with open(eq) as f:
            P("```\n" + f.read().rstrip() + "\n```")
    P("")
    P(table(gap_table(gap, "kth00", lambda r: r["pair"] in ("structure_vs_moving", "solid_vs_moving")), GAP_COLS, GAP_HEADS))
    # ---- Option C
    P("## 6. Option C evidence (matched hit rate, lag-1 autocorrelation)")
    P("")
    P("Shipped conditions only (all conditions are in `p1b_matched_band.csv`). AUC above 0.5: structure cells have the longer runs. The pre-registered reading (PREREG_P1.md section 7.4): support for Option C if the AUC is >= 0.65 or <= 0.35 in a band with >= 100 cells in each group.")
    P("")
    primary = [("lil", "0.05", "15", "structure@static_0_vs_clutter@dynamics_0|-"), ("keble02", "0.2", "10", "structure_vs_clutter|today"),
               ("keble02", "0.2", "10", "structure_vs_clutter|refined"), ("kth00", "0.2", "10", "structure_vs_moving|today")]
    bands = [r for r in load(os.path.join(rd, "p1b_matched_band.csv")) if (r["dataset"], r["res_m"], r["W"], r["pair"]) in primary]
    P(table(bands, ["dataset", "res_m", "W", "pair", "band", "n_structure", "structure_lag1_mean", "n_clutter", "clutter_lag1_mean", "auc_lag1_structure_over_clutter"]))
    # ---- freeze
    P("## 7. Freeze")
    P("")
    pj = os.path.join(a.prereg_dir, "PREREG.json")
    if os.path.exists(pj):
        with open(pj) as f:
            fr = json.load(f)
        for k in ("grid2d", "voxel3d"):
            d = fr[k]
            P("- `%s`: **%s**%s" % (k, d["status"], (", branch %s" % d["branch"]) if "branch" in d else ""))
            if "m0" in d:
                P("  - m0 = %.2f, m1 = %.2f, alpha = beta = %.2f, ceiling = %.4f, n_max = %d, miss = %s" % (d["m0"], d["m1"], d["alpha"], d["ceiling"], d["n_max_undecided"], d["miss_definition"]))
            for r in d.get("reasons", []):
                P("  - reason: %s" % r)
        P("")
        P("Full text: `PREREG.md`.")
    P("")
    # ---- exploratory
    ex = os.path.join(rd, "exploratory")
    P("## 8. Exploratory and post hoc (these runs set nothing)")
    P("")
    rows = []
    if os.path.isdir(ex):
        for fn in sorted(os.listdir(ex)):
            if fn.startswith("gate2d_") and fn.endswith(".meta"):
                m = meta(os.path.join(ex, fn))
                rows.append({"run": fn[:-5], "steps": m.get("steps"), "G1 patches": m.get("g1_accepted"), "G1 median m": "%.4f" % float(m["g1_thickness_m_p50"]),
                             "G1 p90 m": "%.4f" % float(m["g1_thickness_m_p90"]), "G2 median m": "%.4f" % float(m["g2_d_m_p50"])})
        m = meta(os.path.join(ex, "gate_spires_structure_filter.meta"))
        if m:
            rows.append({"run": "keble02, returns inside TLS structure voxels only", "steps": m.get("steps"), "G1 patches": m.get("g1_accepted"),
                         "G1 median m": "%.4f" % float(m["g1_thickness_m_p50"]), "G1 p90 m": "%.4f" % float(m["g1_thickness_m_p90"]), "G2 median m": "%.4f" % float(m["g2_d_m_p50"])})
    P("G1 on slices and on single lasers (same code and thresholds as the gate; limits 0.10 m / 0.20 m in 2D, 0.20 m / 0.40 m in 3D):")
    P("")
    P(table(rows, ["run", "steps", "G1 patches", "G1 median m", "G1 p90 m", "G2 median m"]))
    kc = os.path.join(ex, "keble_clutter_r0.2_W10_today.txt")
    if os.path.exists(kc):
        P("Who are the Keble 02 clutter cells with a high hit rate (`explore_keble_clutter.py`)?")
        P("")
        with open(kc) as f:
            P("```\n" + f.read().rstrip() + "\n```")
        P("")
    # ---- replay
    P("## 9. Replay of the derived test over the calibration run sequences")
    P("")
    rp = os.path.join(rd, "replay", "replay_p1b_out.txt")
    if os.path.exists(rp):
        with open(rp) as f:
            P("```\n" + f.read().rstrip() + "\n```")
    P("")
    P("Shares are over cells of the calibration sequences. `[W ...]` is the Wilson 95 % interval (cells treated as independent), `[B ...]` the block bootstrap over 10 m tiles. Neither is a held-out estimate.")
    P("")
    ar = os.path.join(rd, "advice_replay", "run.log")
    P("## 10. The advisor's replay scripts, re-run")
    P("")
    if os.path.exists(ar):
        with open(ar) as f:
            P("```\n" + f.read().rstrip() + "\n```")
    P("")
    cm = os.path.join(rd, "test_split_stat_compare.md")
    P("## 11. Test-split access record")
    P("")
    P("**What this record proves.** Only that no test-split file was modified (size, mtime and ctime are equal before and after). Reading a file changes none of them, "
      "and `D:` is a 9p mount with `noatime`: the `atime` of files that were certainly read in this phase (the Keble 02 `lidar-clouds.zip`, `gt-tum.txt` and the TLS "
      "`merged-cloud-1cm.pcd`) is identical in the two records. The advice section 7 acceptance check on `atime` therefore cannot be verified on this mount. "
      "The evidence that other test files were not opened is the step logs and the committed scripts (a search of all committed scripts, logs and exploratory logs "
      "finds test-split paths only in the stat scripts: Opus review of phase 1b, finding 2). For P3 every measurement step records an `strace -f -e trace=openat,open` "
      "log, committed beside the step log (`PREREG_P1B.md`, Amendment 3).")
    P("")
    if os.path.exists(cm):
        with open(cm) as f:
            txt = f.read()
        P(txt)
    P("")
    P("## 12. Tests and mutation evidence")
    P("")
    for fn, title in (("mutation_record_pass1.md", "pass 1"), ("mutation_record.md", "pass 2 (final tests)")):
        mp = os.path.join(rd, fn)
        if os.path.exists(mp):
            with open(mp) as f:
                lines = [l for l in f.read().splitlines() if l.startswith("Mutants:")]
            P("- mutation %s: %s (`%s`)" % (title, lines[0] if lines else "n/a", fn))
    P("")
    # ---- review findings (static text and one table read from committed P1 tables)
    P("## 13. Open items from the Opus review of phase 1b (for the lead; nothing here changes a verdict or a definition)")
    P("")
    P("### 13.1 Time base of the LILocBench clutter sequence (`dynamics_0`)")
    P("")
    P("Advice section 4: if LIL fails G1 or G2, stop and re-examine the time base first. Phase 1b stopped but did not look. The phase 1 offset search already shows a "
      "per-laser disagreement on `dynamics_0` only (fewest occupied cells, front and rear laser alone; `results_p1/meta/lil_offset_*.csv`):")
    P("")
    rows = []
    p1 = os.path.join(rd, "..", "results_p1", "meta")
    for sq in ("mapping", "static_0", "dynamics_0"):
        o = laser_optima(os.path.join(p1, "lil_offset_%s.csv" % sq))
        if o:
            rows.append({"sequence": sq, "front_dt_s": o["c_front"][0], "front_cells": o["c_front"][1], "rear_dt_s": o["c_rear"][0], "rear_cells": o["c_rear"][1],
                         "sum_dt_s": o["score"][0], "sum_cells": o["score"][1]})
    P(table(rows, ["sequence", "front_dt_s", "front_cells", "rear_dt_s", "rear_cells", "sum_dt_s", "sum_cells"],
            ["sequence", "front optimum dt (s)", "cells", "rear optimum dt (s)", "cells", "both lasers optimum dt (s)", "cells"]))
    P("Run B used one offset, -0.13 s, for all three sequences. On `dynamics_0` the rear laser is best at -0.06 s (7258 cells; 8904 at -0.13 s). "
      "The reviewer's post hoc check (own code, files under `/mnt/d/wsl/strata/review_p1b/`, not committed, not pre-registered, not reproduced here): robust wall width "
      "3.46 x 1.4826 x MAD of the perpendicular offsets in the accepted linear patches is 0.172 m for the `dynamics_0` rear laser against 0.075 m for the `static_0` rear laser; "
      "with the rear frames of `dynamics_0` taken at -0.06 s it is 0.120 m. The pre-registered G1 statistic on `dynamics_0` would move from median 0.185 m (485 patches) to 0.140 m "
      "(581 patches); `q_c` (0.05 m, W = 15) from 0.1725 to 0.1707, so the conditional pair stays (0.20, 0.70); `structure@dynamics_0` q10 from 0.25 to 0.36. "
      "The W = 15 cell table of `dynamics_0` rebuilt at -0.13 s is byte-identical to the run B cache. "
      "**The lead must settle the `dynamics_0` rear-laser offset (a pre-registered per-laser rule, as an amendment) before waiving any gate for `dynamics_0`.**")
    P("")
    P("### 13.2 `n_max_undecided`")
    P("")
    P("`LEAD_DECISIONS_P1.md` L-6 fixes 64. `PREREG_P1B.md` section 7 replaced it with a rule (smallest multiple of 16 with P(undecided) <= 0.03), which gives 80. "
      "Exact undecided shares under the engine rule (no floor before n >= 24; `derive_defaults.py`, re-computed and equal to the reviewer's own dynamic program):")
    P("")
    P("| pair | P(undecided) at 64 | P(undecided) at 80 | rule |")
    P("|---|---|---|---|")
    P("| (0.15, 0.65) | 0.0314 | 0.0113 | 80 |")
    P("| (0.20, 0.70) | 0.0388 | 0.0150 | 80 |")
    P("")
    P("The value that binds P2 is for the lead to record in `LEAD_DECISIONS_P1.md`: the rule (80), or 64 with the 0.039 undecided share reported.")
    P("")
    P("### 13.3 G1 does not measure what it claims")
    P("")
    P("The gates match the spec. The reviewer's independent C++ (own reader, RNG, nearest-neighbour search and eigen code) reproduces G2 on `static_0` exactly "
      "(1,445,199 query points, matched 0.999698, median 0.001326 m, p90 0.005970 m) and G1 within sampling (427 patches, 0.1707 / 0.2550 m against the branch's 391, 0.1705 / 0.2545 m). "
      "But sqrt(12 lambda_min) does not resist off-line points. On the same accepted patches the robust core width is 0.076 m on `static_0` (the spec predicts 0.077) and 0.063 m on `mapping`; "
      "on the run A cache, which has the known 0.13 s error, it is 0.131 m. So the 0.17 to 0.19 m G1 failures come from second surfaces inside 'linear' patches, not from pose smear. "
      "On Keble 02, G1 fails (0.32 m) while the poses are good. G2 cannot see smear (`deviations.md`, item 7). "
      "Any replacement gate is a second gate change made after seeing data: it must be committed as an amendment with this chronology and reported as such. "
      "A robust-width G1 at the spec's 0.10 m limit separates run A from run B in the reviewer's post hoc check; that check is not pre-registered and must not be presented as such. "
      "**This blocks the freeze; the decision is the lead's.**")
    P("")
    out = "\n".join(L)
    with open(a.out, "w") as f:
        f.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
