#!/usr/bin/env python3
"""Formats the phase 1 result tables into P1_REPORT.md. Computes no statistic: every number is
copied from the CSV and meta files written by hitrate_probe and analyze_p1.py. The only logic is
filtering rows and comparing a meta value with a fixed bound of PREREG_P1.md (gate verdicts).
usage: python3 -I make_report.py --results-dir results_p1 --out results_p1/P1_REPORT.md
"""
import argparse
