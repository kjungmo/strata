def read_csv(path):
    if not os.path.exists(path):
        return [], []
    with open(path) as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def read_dicts(path):
    h, rows = read_csv(path)
    return h, [dict(zip(h, r)) for r in rows]


def read_meta(path):
    d = {}
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                if "=" in line:
                    k, v = line.rstrip("\n").split("=", 1)
                    d[k] = v
    return d


def fnum(x, default=float("nan")):
    try:
        return float(x)
    except (TypeError, ValueError):
        return default


def md_table(head, rows):
    if not rows:
        return "_no rows_\n"
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out) + "\n"


def cols_of(dicts, cols, pred=lambda d: True):
    return [[d.get(c, "n/a") for c in cols] for d in dicts if pred(d)]


def thickness_verdict(meta):
    try:
        med, p90, used = float(meta["thickness_m_p50"]), float(meta["thickness_m_p90"]), int(meta["used"])
    except (KeyError, ValueError):
        return "n/a"
    return "PASS" if (med <= 0.20 and p90 <= 0.40 and used >= 500) else "FAIL"


def lil_pose_verdict(c, skew_bound):
    """PREREG_P1.md section 5, LILocBench pose sanity. Returns 'PASS' or 'FAIL (reasons)'."""
    if not c:
        return "n/a"
    bad = []
    if c.get("counts_match") != "1":
        bad.append("scan counts differ")
    if fnum(c.get("gt_max_gap_s")) > 0.2:
        bad.append("GT gap > 0.2 s")
    if fnum(c.get("gt_max_step_m")) > 0.1:
        bad.append("GT step > 0.1 m")
    steps = fnum(c.get("steps"))
    if fnum(c.get("scans_dropped_no_pose")) > 0.01 * 2 * steps:
        bad.append("scans dropped > 1 %")
    if fnum(c.get("beams_dropped_no_pose")) > 0.01 * fnum(c.get("beams_total")):
        bad.append("beams dropped > 1 %")
    if fnum(c.get("tf_front_spread")) >= 1e-6 or fnum(c.get("tf_rear_spread")) >= 1e-6:
        bad.append("extrinsic spread")
    if fnum(c.get("max_front_rear_stamp_skew_s")) > skew_bound:
        bad.append("pair skew %s s > %s s" % (c.get("max_front_rear_stamp_skew_s"), skew_bound))
    return "PASS" if not bad else "FAIL (" + "; ".join(bad) + ")"


def curve_rows(csv_path, step=0.02):
    """Score of the start, end and single anchors every `step` s, copied from the search file."""
    h, rows = read_dicts(csv_path)
    by = {}
    for r in rows:
        by[(r["anchor"], round(float(r["dt_s"]), 4))] = r["score"]
    out = []
    k = -15
    while k <= 15:
        dt = round(k * step, 4)
        out.append(["%+.2f" % dt] + [by.get((a, dt), "n/a") for a in ("start", "end", "single")])
        k += 1
    return out


def score_at(csv_path, anchor, dt):
    h, rows = read_dicts(csv_path)
    for r in rows:
        if r["anchor"] == anchor and abs(float(r["dt_s"]) - dt) < 1e-9:
            return r["score"]
    return "n/a"


def best_single(csv_path):
    h, rows = read_dicts(csv_path)
    best = None
    for r in rows:
        if r["anchor"] == "single" and (best is None or float(r["score"]) < float(best["score"])):
            best = r
    return ("%s at dt %s" % (best["score"], best["dt_s"])) if best else "n/a"


def gap_pick(rows, dataset, pair, n_min=None):
    return [r for r in rows if r["dataset"] == dataset and r["pair"] == pair and (n_min is None or r["N_min"] == str(n_min))]


