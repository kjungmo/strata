#!/usr/bin/env python3
"""Formats the phase 1 result tables into P1_REPORT.md. Computes no statistic: every number is
copied from the CSV and meta files written by hitrate_probe and analyze_p1.py.
usage: python3 -I make_report.py --results-dir results_p1 --out results_p1/P1_REPORT.md
"""
import argparse
import csv
import glob
import os
import sys


def read_csv(path):
    if not os.path.exists(path):
        return [], []
    with open(path) as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def read_meta(path):
    d = {}
    if os.path.exists(path):
        with open(path) as f:
            for line in f:
                if "=" in line:
                    k, v = line.rstrip("\n").split("=", 1)
                    d[k] = v
    return d


def md_table(head, rows):
    if not rows:
        return "_no rows_\n"
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    for r in rows:
        out.append("| " + " | ".join(r) + " |")
    return "\n".join(out) + "\n"


def pick(head, rows, cols, where=None):
    idx = [head.index(c) for c in cols]
    out = []
    for r in rows:
        if where and not all(r[head.index(k)] == v for k, v in where.items()):
            continue
        out.append([r[i] for i in idx])
    return out


def gate_verdict(meta, kind):
    try:
        med, p90, used = float(meta["thickness_m_p50"]), float(meta["thickness_m_p90"]), int(meta["used"])
    except (KeyError, ValueError):
        return "n/a"
    ok = med <= 0.20 and p90 <= 0.40 and used >= 500
    return "PASS" if ok else "FAIL"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    R = a.results_dir
    L = []
    L.append("# P1_REPORT: calibration hit-rate statistics (generated)\n")
    L.append("Generated by `make_report.py` from the files next to it. Definitions: `PREREG_P1.md`. "
             "Nothing here chooses `(m0, m1)`; the `gap_ge_0.15` column is a mechanical read-out of the first line of the "
             "escalation rule, not a decision.\n")
    man = os.path.join(R, "run_manifest.txt")
    if os.path.exists(man):
        L.append("## Run manifest\n\n```\n" + open(man).read() + "```\n")
    # gates
    L.append("## Quality gates (pre-registered rule: median <= 0.20 m, p90 <= 0.40 m, >= 500 patches)\n")
    rows = []
    kg = read_meta(os.path.join(R, "meta", "kth_gate.meta"))
    rows.append(["KITTI 00 (poses)", "pose_ok=" + kg.get("pose_ok", "n/a"), "max step %s m, max turn %s deg" % (kg.get("pose_max_step_m", "n/a"), kg.get("pose_max_rot_deg", "n/a")), "", "", ""])
    rows.append(["KITTI 00 (wall thickness, m)", "", "patches %s" % kg.get("used", "n/a"),
                 "p10 %.3f p50 %.3f p90 %.3f" % tuple(float(kg.get(k, "nan")) for k in ("thickness_m_p10", "thickness_m_p50", "thickness_m_p90")),
                 "p50 = %.2f cells at 0.2 m" % float(kg.get("thickness_cells_p50", "nan")), gate_verdict(kg, "kth")])
    for s in ("mapping", "static_0", "dynamics_0"):
        g = read_meta(os.path.join(R, "meta", "lil_gate_%s.meta" % s))
        c = read_meta(os.path.join(R, "meta", "lil_convert_%s.meta" % s))
        rows.append(["LIL %s (wall thickness, m)" % s, "", "patches %s" % g.get("used", "n/a"),
                     "p10 %.3f p50 %.3f p90 %.3f" % tuple(float(g.get(k, "nan")) for k in ("thickness_m_p10", "thickness_m_p50", "thickness_m_p90")),
                     "p50 = %.2f cells at 0.05 m" % float(g.get("thickness_cells_p50", "nan")), gate_verdict(g, "lil")])
        rows.append(["LIL %s (poses)" % s, "counts_match=%s" % c.get("counts_match", "n/a"),
                     "scans dropped %s of %s steps; beams dropped %s of %s" % (c.get("scans_dropped_no_pose"), c.get("steps"), c.get("beams_dropped_no_pose"), c.get("beams_total")),
                     "max GT gap %s s, max GT step %s m" % (c.get("gt_max_gap_s"), c.get("gt_max_step_m")),
                     "max front/rear skew %s s; tf spread %s/%s" % (c.get("max_front_rear_stamp_skew_s"), c.get("tf_front_spread"), c.get("tf_rear_spread")), ""])
    L.append(md_table(["sequence", "check", "detail", "values", "values 2", "verdict"], rows))
    verdicts = [r[5] for r in rows if r[5]]
    nfail = sum(1 for v in verdicts if v != "PASS")
    L.append("**Gate outcome: %d of %d wall-thickness gates failed.** PREREG_P1 section 5: a failing sequence is still run, "
             "is reported, and does not enter a headline table. %s\n" % (
                 nfail, len(verdicts),
                 "Every sequence failed, so there is no headline table: every number below belongs to an EXCLUDED sequence "
                 "and is reported only as such." if nfail == len(verdicts) else
                 "The sequences marked FAIL are EXCLUDED; the others are headline."))
    bad = []
    for fn in sorted(glob.glob(os.path.join(R, "meta", "*cells_*.meta"))):
        m = read_meta(fn)
        if m.get("observer_inconsistent", "0") != "0" or m.get("window_origin_missing", "0") != "0":
            bad.append(os.path.basename(fn))
    L.append("Consistency rail (`observer_inconsistent = 0`, `window_origin_missing = 0` in every measurement meta file): %s\n" %
             ("holds in all measurement runs" if not bad else "VIOLATED in " + ", ".join(bad)))
    # labels
    L.append("## Label counts\n")
    rows = []
    for r in ("0.2", "0.1"):
        m = read_meta(os.path.join(R, "meta", "labels_r%s.meta" % r))
        if m:
            rows.append(["KITTI 00", r, m["cells_moving"], m["cells_static_structure"], m["cells_static_ground"], m["cells_ego_excluded"], m["gt_dynamic_points"], m["gt_dynamic_points_ego"]])
    L.append(md_table(["dataset", "res_m", "moving", "static_structure", "static_ground", "ego (excluded)", "GT dynamic points", "of which ego"], rows))
    rows = []
    for r, rf in (("0.05", "0.05"), ("0.1", "0.10")):
        m = read_meta(os.path.join(R, "meta", "lil_ref_r%s.meta" % rf))
        if m:
            rows.append(["LILocBench mapping", r, m["cells_ref_occupied"], m["cells_ref_free"], m["cells_ref_free_near_occupied"], m["cells_touched"]])
    L.append(md_table(["dataset", "res_m", "ref occupied", "ref free", "free near occupied", "cells touched"], rows))
    # gap tables
    h, rows = read_csv(os.path.join(R, "p1_gap.csv"))
    L.append("## q_s, q_c and gap (primary N_min = 5 first; N_min 3 and 10 are sensitivity)\n")
    cols = ["dataset", "res_m", "W", "pair", "N_min", "n_structure", "n_clutter", "q_s_p10", "q_c_p90", "gap",
            "gap_ci95_iid_lo", "gap_ci95_iid_hi", "gap_ci95_block_lo", "gap_ci95_block_hi", "gap_ge_0.15", "auc_rate"]
    L.append(md_table(cols, pick(h, rows, cols)) if h else "_missing_\n")
    # touched windows
    h, rows = read_csv(os.path.join(R, "p1_touched_windows.csv"))
    L.append("## Touched windows per cell (can a cell reach a sequential threshold at all?)\n")
    L.append(md_table(h, rows) if h else "_missing_\n")
    h, rows = read_csv(os.path.join(R, "p1_runs.csv"))
    L.append("## Run-length and transition statistics (N_min = 5)\n\nswitch_ratio: observed / expected hit-miss switches given each cell's own hit rate (1 = no run structure; below 1 = longer runs).\n")
    L.append(md_table(h, rows) if h else "_missing_\n")
    h, rows = read_csv(os.path.join(R, "p1_matched_band.csv"))
    L.append("## Run structure at matched hit rate (evidence for or against Option C)\n")
    L.append(md_table(h, rows) if h else "_missing_\n")
    h, rows = read_csv(os.path.join(R, "p1_diversity.csv"))
    L.append("## Viewpoint diversity (greedy count of sensor positions at least 1 m apart)\n")
    L.append(md_table(h, rows) if h else "_missing_\n")
    h, rows = read_csv(os.path.join(R, "p1_percentiles.csv"))
    L.append("## Per-cell hit-rate percentiles\n")
    L.append(md_table(h, rows) if h else "_missing_\n")
    h, rows = read_csv(os.path.join(R, "p1_inventory.csv"))
    L.append("## Runs included (every condition; missing ones are listed)\n")
    L.append(md_table(h, rows) if h else "_missing_\n")
    figs = sorted(glob.glob(os.path.join(R, "fig_hist_*.png")))
    if figs:
        L.append("## Figures\n")
        for f in figs:
            L.append("![%s](%s)\n" % (os.path.basename(f), os.path.basename(f)))
    if os.path.exists(os.path.join(R, "deviations.md")):
        L.append("## Deviations and notes\n\n" + open(os.path.join(R, "deviations.md")).read())
    with open(a.out, "w") as f:
        f.write("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
